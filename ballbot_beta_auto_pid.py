                    Tx = tuner_x.control(theta_x)
                    done, Ku, Pu = tuner_x.update(theta_x, t_now)
                    if done:
                        # Tyreus–Luyben PID (safer for oscillatory/unstable plants)
                        # References commonly use: Kp=0.454Ku, Ti=2.2Pu, Td=0.159Pu
                        Kp = 0.454 * Ku
                        Ti = 2.2 * Pu
                        Td = 0.159 * Pu
                        Ki = Kp / Ti if Ti > 1e-3 else 0.0

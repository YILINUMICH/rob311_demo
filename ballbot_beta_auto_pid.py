class RelayAutoTuner:
    """
    Relay (on-off) autotuner for a single axis.

    Applies a relay control u = +/- h depending on sign(error). Measures the
    resulting sustained oscillation's amplitude (a) and period (Pu) from theta
    zero-crossings and peaks, then computes Ziegler–Nichols PID gains.
    """

    def __init__(self, axis_name: str, relay_amp: float, angle_limit: float, dt: float):
        self.axis_name = axis_name
        self.h = relay_amp
        self.angle_limit = angle_limit
        self.dt = dt
        # Detection state
        self.prev_theta = 0.0
        self.prev_sign = 0
        self.last_cross_time = None
        self.prev_pos_cross_time = None
        self.periods = []
        self.window_max = 0.0
        self.window_min = 0.0
        self.amp_list = []
        self.t = 0.0

    def control(self, theta: float) -> float:
        # Relay command based on sign of theta (error = 0 - theta)
        # If theta > 0 (lean +), command negative torque to pull back
        return -self.h if theta > 0 else self.h

    def update(self, theta: float, t_now: float):
        """Update oscillation measurement; call each loop.
        Returns tuple (done, Ku, Pu) when enough data is collected.
        """
        self.t = t_now
        # Safety
        if abs(theta) > self.angle_limit:
            raise RuntimeError(f"{self.axis_name} autotune aborted: |theta| too large ({np.degrees(theta):.1f} deg)")

        # Track extrema between zero crossings
        self.window_max = max(self.window_max, theta)
        self.window_min = min(self.window_min, theta)

        sign_now = 1 if theta >= 0 else -1
        crossed = (sign_now != self.prev_sign and self.prev_sign != 0)
        if crossed:
            # Zero-crossing detected
            if sign_now > 0:
                # Positive-going crossing: measure full period from previous positive crossing
                if self.prev_pos_cross_time is not None:
                    Pu = t_now - self.prev_pos_cross_time
                    self.periods.append(Pu)
                    # Amplitude a is half the peak-to-peak in last half-cycle window
                    a = 0.5 * (self.window_max - self.window_min)
                    if a > 1e-6:
                        self.amp_list.append(a)
                self.prev_pos_cross_time = t_now
            # Reset window for next half-cycle
            self.window_max = -1e9
            self.window_min = 1e9

        self.prev_sign = sign_now

        # Decide completion: need at least 2-3 stable periods
        if len(self.periods) >= 3 and len(self.amp_list) >= 3:
            Pu_avg = float(np.median(self.periods[-3:]))
            a_avg = float(np.median(self.amp_list[-3:]))
            # Basic sanity: recent variation small
            Pu_var = np.std(self.periods[-3:]) / Pu_avg if Pu_avg > 0 else 1.0
            a_var = np.std(self.amp_list[-3:]) / a_avg if a_avg > 0 else 1.0
            if Pu_var < 0.15 and a_var < 0.15:
                Ku = 4 * self.h / (np.pi * a_avg)
                return True, Ku, Pu_avg
        return False, None, None



    controller = PS4InputHandler(interface="/dev/input/js0", connecting_using_ds4drv=False)
    controller_thread = threading.Thread(target=controller.listen, args=(10,))
    controller_thread.daemon = True
    controller_thread.start()
    print("✓ PS4 Controller initialized")

    # Inner PID placeholders (gains will be auto-tuned)
    inner_pid_x = PIDController(Kp=6.0, Ki=0.0, Kd=0.5, dt=DT, integral_limit=0.5, output_limit=(-PWM_MAX, PWM_MAX))
    inner_pid_y = PIDController(Kp=6.0, Ki=0.0, Kd=0.5, dt=DT, integral_limit=0.5, output_limit=(-PWM_MAX, PWM_MAX))

    print("\nStarting control loop in 0.5 seconds...")
    time.sleep(0.5)

    # Data header

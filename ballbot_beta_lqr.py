class ExtendedKalmanFilter:
    """
    Extended Kalman Filter for state estimation.
    
    Fuses noisy measurements (IMU angles, encoder positions/velocities) to
    estimate full state with reduced noise.
    
    State: x = [θx, θy, θ̇x, θ̇y, φx, φy, φ̇x, φ̇y]ᵀ
    Measurements: z = [θx_imu, θy_imu, φx_enc, φy_enc]ᵀ
    
    Process model: x[k+1] = A*x[k] + B*u[k] + w  (w ~ N(0, Q_proc))
    Measurement model: z[k] = H*x[k] + v  (v ~ N(0, R_meas))
    """
    
    def __init__(self, A_d, B_d, dt):
        """
        Args:
            A_d: Discrete-time state matrix (8×8)
            B_d: Discrete-time input matrix (8×2)
            dt: Sampling period [s]
        """
        self.A = A_d
        self.B = B_d
        self.dt = dt
        
        # State dimension
        self.n = 8
        
        # Measurement matrix H: we measure [θx, θy, φx, φy]
        # z = [θx, θy, φx, φy]ᵀ = H*x
        self.H = np.array([
            [1, 0, 0, 0, 0, 0, 0, 0],  # θx
            [0, 1, 0, 0, 0, 0, 0, 0],  # θy
            [0, 0, 0, 0, 1, 0, 0, 0],  # φx
            [0, 0, 0, 0, 0, 1, 0, 0],  # φy
        ])
        
        # Process noise covariance Q (tune these)
        # Higher values = trust model less, trust measurements more
        q_angle = 1e-4       # Process noise for angles
        q_vel = 1e-3         # Process noise for velocities
        q_pos = 1e-4         # Process noise for positions
        q_pos_vel = 1e-3     # Process noise for position velocities
        self.Q_proc = np.diag([q_angle, q_angle, q_vel, q_vel, 
                               q_pos, q_pos, q_pos_vel, q_pos_vel])
        
        # Measurement noise covariance R (tune these)
        # Based on sensor characteristics
        r_imu = np.radians(0.5)**2    # IMU noise variance [rad²]
        r_enc = np.radians(0.2)**2    # Encoder odometry noise [rad²]
        self.R_meas = np.diag([r_imu, r_imu, r_enc, r_enc])
        
        # Initial state estimate and covariance
        self.x_hat = np.zeros((self.n, 1))
        self.P = np.eye(self.n) * 1.0  # Initial uncertainty
        
        print("✓ EKF initialized")
    
    def predict(self, u):
        """
        Prediction step: propagate state estimate using dynamics.
        
        Args:
            u: Control input (2×1)
        """
        # State prediction: x̂[k|k-1] = A*x̂[k-1|k-1] + B*u[k-1]
        self.x_hat = self.A @ self.x_hat + self.B @ u.reshape(-1, 1)
        
        # Covariance prediction: P[k|k-1] = A*P[k-1|k-1]*Aᵀ + Q
        self.P = self.A @ self.P @ self.A.T + self.Q_proc
    
    def update(self, z_meas):
        """
        Update step: correct state estimate using measurements.
        
        Args:
            z_meas: Measurement vector (4×1) = [θx, θy, φx, φy]ᵀ
        """
        z_meas = z_meas.reshape(-1, 1)
        
        # Innovation: y = z - H*x̂[k|k-1]
        y = z_meas - self.H @ self.x_hat
        
        # Innovation covariance: S = H*P[k|k-1]*Hᵀ + R
        S = self.H @ self.P @ self.H.T + self.R_meas
        
        # Kalman gain: K = P[k|k-1]*Hᵀ*S⁻¹
        K = self.P @ self.H.T @ linalg.inv(S)
        
        # State update: x̂[k|k] = x̂[k|k-1] + K*y
        self.x_hat = self.x_hat + K @ y
        
        # Covariance update: P[k|k] = (I - K*H)*P[k|k-1]
        I = np.eye(self.n)
        self.P = (I - K @ self.H) @ self.P
    
    def get_state(self):
        """
        Get current state estimate.
        
        Returns:
            x_hat: State estimate (8×1)
        """
        return self.x_hat.flatten()



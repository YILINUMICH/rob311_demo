class LQRController:
    """
    Linear Quadratic Regulator for optimal state feedback.
    
    Computes control law u = -K*x that minimizes:
        J = Σ (xᵀQx + uᵀRu)
    
    Where:
    - Q: State cost matrix (penalizes deviations from upright/stationary)
    - R: Control cost matrix (penalizes motor effort)
    - K: Optimal feedback gain matrix
    """
    
    def __init__(self, A_d, B_d, Q, R):
        """
        Args:
            A_d: Discrete-time state matrix (n×n)
            B_d: Discrete-time input matrix (n×m)
            Q: State cost matrix (n×n), positive semi-definite
            R: Control cost matrix (m×m), positive definite
        """
        self.A_d = A_d
        self.B_d = B_d
        self.Q = Q
        self.R = R
        
        # Solve discrete-time algebraic Riccati equation (DARE)
        # P = AᵀPA - AᵀPB(R + BᵀPB)⁻¹BᵀPA + Q
        try:
            P = linalg.solve_discrete_are(A_d, B_d, Q, R)
            # Compute optimal gain: K = (R + BᵀPB)⁻¹BᵀPA
            self.K = linalg.solve(R + B_d.T @ P @ B_d, B_d.T @ P @ A_d)
            print(f"✓ LQR gains computed successfully")
            print(f"  K shape: {self.K.shape}")
            print(f"  K =\n{self.K}")
        except Exception as e:
            print(f"ERROR: LQR gain computation failed: {e}")
            # Fallback to zero gains (open-loop)
            self.K = np.zeros((B_d.shape[1], A_d.shape[0]))
    
    def control(self, x_state):
        """
        Compute control input for given state.
        
        Args:
            x_state: Current state vector (8×1)
            
        Returns:
            u: Control input (2×1) = [Tx, Ty]ᵀ
        """
        u = -self.K @ x_state
        return u



def get_linearized_dynamics(dt):
    """
    Compute linearized continuous-time dynamics A, B for balancing robot.
    
    Simplified model: 
    - State: x = [θx, θy, θ̇x, θ̇y, φx, φy, φ̇x, φ̇y]ᵀ (8 states)
    - Control: u = [Tx, Ty]ᵀ (2 inputs)
    - Dynamics linearized around upright equilibrium (θ=0, φ=0)
    
    Using inverted pendulum approximation:
    θ̈ ≈ (M_BOT*g*H/J_eff)*θ - (B/J_eff)*θ̇ + (1/J_eff)*T
    φ̈ ≈ -θ̈  (ball motion coupled to body tilt)
    
    Returns:
        A: 8×8 state matrix (continuous-time)
        B: 8×2 input matrix (continuous-time)
        A_d: 8×8 discrete-time state matrix
        B_d: 8×2 discrete-time input matrix
    """
    # Effective inertia
    J_eff = J_BOT + M_BOT * H**2 + J_BALL
    
    # Continuous-time dynamics
    A = np.zeros((8, 8))
    B = np.zeros((8, 2))
    
    # X-axis dynamics (θx, θ̇x, φx, φ̇x)
    # θ̇x = θ̇x
    A[0, 2] = 1.0
    # θ̈x = (M*g*H/J)*θx - (B/J)*θ̇x + (1/J)*Tx
    A[2, 0] = (M_BOT * G * H) / J_eff
    A[2, 2] = -B / J_eff
    B[2, 0] = 1.0 / J_eff
    # φ̇x = φ̇x
    A[4, 6] = 1.0
    # φ̈x = -θ̈x (simplified coupling)
    A[6, 0] = -(M_BOT * G * H) / J_eff
    A[6, 2] = B / J_eff
    B[6, 0] = -1.0 / J_eff
    
    # Y-axis dynamics (θy, θ̇y, φy, φ̇y) - identical structure
    A[1, 3] = 1.0
    A[3, 1] = (M_BOT * G * H) / J_eff
    A[3, 3] = -B / J_eff
    B[3, 1] = 1.0 / J_eff
    A[5, 7] = 1.0
    A[7, 1] = -(M_BOT * G * H) / J_eff
    A[7, 3] = B / J_eff
    B[7, 1] = -1.0 / J_eff
    
    # Discretize using matrix exponential (exact for linear systems)
    # x[k+1] = A_d*x[k] + B_d*u[k]
    n = A.shape[0]
    m = B.shape[1]
    # Augmented matrix for discretization
    M = np.zeros((n+m, n+m))
    M[:n, :n] = A * dt
    M[:n, n:] = B * dt
    M_exp = linalg.expm(M)
    A_d = M_exp[:n, :n]
    B_d = M_exp[:n, n:]
    
    return A, B, A_d, B_d


